@app.get("/devices/{name}")
def get_device(name: str):
    device = devices.find_one({"name": name}, {"_id": 0})
    if device is None:
        raise HTTPException(status_code=404,
                            detail="No device called " + name)
    return device #The loop is gone: the database does the searching. find_one gives back None when nothing matches, and None becomes your 404.

#adjust post requesy to prevent a type error when i post a device in the mac format
@app.post("/devices", status_code=201)
def create_device(device: Device):
    new_device = device.model_dump()
    try:
        devices.insert_one(new_device)
    except DuplicateKeyError:
        raise HTTPException(status_code=409, detail=f"Device with name {device.name} already exists")
    new_device.pop("_id")
    return new_device

@app.post("/readings", status_code=201)
def create_reading(reading: Reading):
    if devices.find_one({"mac": reading.mac}) is None:
        raise HTTPException(status_code=404,
            detail="No device with MAC " + reading.mac)
    new_reading = reading.model_dump()
    new_reading["time"] = datetime.now(timezone.utc)
    readings.insert_one(new_reading)
    new_reading.pop("_id")
    return new_reading

