#specify a limit on the number of readings returned, and allow filtering by mac address
# we generally don't want to get all the readings in a database
@app.get("/readings")
def get_readings(mac: str | None = None, limit: int = 10, since:datetime | None = None):
    query = {}
    if mac is not None:
        query["mac"] = mac
    return list(readings.find(query, {"_id": 0})
                        .sort("time", -1).limit(limit))


@app.get("/readings/latest")
def get_latest_reading(mac: str | None = None):
    query = {}
    if mac is not None:
        query["mac"] = mac
    reading = readings.find_one(query, {"_id": 0}, sort=[("time", -1)])
    if reading is None:
        raise HTTPException(status_code=404, detail="No readings yet")
    return reading