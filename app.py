from fastapi import FastAPI, HTTPException
from pydantic import BaseModel
import os #allows python to interact with files on computer 
from  dotenv import load_dotenv #stores connection string in memory 
from pymongo import MongoClient #a client python uses to connect to MongoDB

load_dotenv() #loads connection string from .env file into memory
client = MongoClient(os.getenv("MONGODB_URI")) #creates a client instance, an object that stores connection to the MongoDB servers, finding string in env file and making connection to databse
db = client["ecse038"] #accesses the database
devices = db["devices"] #creates the collection called devices 

app = FastAPI()


class Device(BaseModel):
    name: str
    room: str
    temp: float
    online: bool


readings = []


@app.get("/devices")
def get_devices():
    return list(devices.find({},{"_id":0})) #the second {} says which fields to return, in this case we want all fields except the _id field, which is automatically generated by MongoDB and is not needed for our purposes.
#the first {} is a filter, which we are not using in this case, so we leave it empty. The find() method returns a cursor, which is an iterator that allows us to iterate over the results of the query. We convert the cursor to a list using the list() function, so that we can return it as a JSON response.

